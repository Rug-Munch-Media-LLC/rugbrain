"""Confidence Scorer — mathematical probability metrics for RAG-generated claims.

Adds a ``confidence_score`` (0.0–1.0) to every claim generated by the RAG
system, based on:
1. **Source quality**: How authoritative the source is (e.g., on-chain data > forum post)
2. **Source freshness**: How recent the data is (temporal decay)
3. **Source count**: How many independent sources support the claim
4. **Embedding similarity**: How close the retrieved chunks matched the query
5. **Reranker score**: The cross-encoder's relevance score (if available)
"""

from __future__ import annotations

from typing import Any

# Source quality tiers (0.0–1.0)
SOURCE_QUALITY: dict[str, float] = {
    # On-chain (highest confidence)
    "onchain_rpc": 1.0,
    "onchain_verified": 1.0,
    "smart_contract_audited": 0.95,
    "scanner_result": 0.9,
    # Regulatory
    "sec_filing": 0.95,
    "sec_enforcement": 0.95,
    "ofac_sanctions": 0.95,
    "court_filing": 0.95,
    # Market data
    "coingecko": 0.85,
    "defillama": 0.85,
    "cex_ticker": 0.8,
    # News & social
    "news_tier1": 0.7,
    "news_tier2": 0.5,
    "governance_forum": 0.6,
    "github_commit": 0.7,
    "audit_report": 0.9,
    # Social (lowest confidence)
    "telegram": 0.3,
    "discord": 0.3,
    "twitter": 0.2,
    "reddit": 0.15,
    "unknown": 0.1,
}

# Half-life for freshness decay (hours)
FRESHNESS_HALFLIFE_HOURS = 168.0  # 7 days


def score_confidence(
    sources: list[dict[str, Any]],
    query_similarity: float = 0.0,
    reranker_score: float | None = None,
    source_count_threshold: int = 3,
) -> dict[str, Any]:
    """Compute a confidence score for a generated claim.

    Args:
        sources: List of source dicts, each with ``type``, ``score``, and
                 optionally ``timestamp``, ``relevance_score``.
        query_similarity: The embedding similarity of the best-matching chunk
                          (0.0–1.0).
        reranker_score: The cross-encoder reranker score (0.0–1.0), if available.
        source_count_threshold: Number of independent sources needed for
                                "high confidence" (default 3).

    Returns:
        Dict with ``confidence_score`` (0.0–1.0), ``confidence_label``
        (``"high"``, ``"medium"``, ``"low"``, ``"insufficient"``), and a
        ``breakdown`` dict explaining the factors.
    """
    import math
    import time

    if not sources:
        return {
            "confidence_score": 0.0,
            "confidence_label": "insufficient",
            "breakdown": {"sources_count": 0, "reason": "no_sources"},
        }

    # 1. Source quality score: average of best source quality tiers
    quality_scores = []
    for src in sources:
        src_type = src.get("type", "unknown")
        quality = SOURCE_QUALITY.get(src_type, SOURCE_QUALITY["unknown"])
        quality_scores.append(quality)

    if not quality_scores:
        quality_scores = [SOURCE_QUALITY["unknown"]]

    avg_quality = sum(quality_scores) / len(quality_scores)

    # 2. Source count factor: more sources = higher confidence (diminishing returns)
    count_factor = min(1.0, len(sources) / source_count_threshold)
    count_factor = math.sqrt(count_factor)  # diminishing returns

    # 3. Freshness factor: recent sources are better
    freshness_factors = []
    now = time.time()
    for src in sources:
        ts = src.get("timestamp")
        if ts:
            age_hours = (now - float(ts)) / 3600.0 if isinstance(ts, (int, float)) else 0.0
            if age_hours < 0:
                age_hours = 0.0
            freshness = math.pow(2.0, -age_hours / FRESHNESS_HALFLIFE_HOURS)
            freshness_factors.append(freshness)

    avg_freshness = sum(freshness_factors) / len(freshness_factors) if freshness_factors else 0.5

    # 4. Embedding similarity factor
    sim_factor = min(1.0, max(0.0, query_similarity))

    # 5. Reranker factor (if available). NOTE: `is not None` — an explicit
    # 0.0 is a meaningful "totally irrelevant" score, not a missing value.
    rerank_factor = min(1.0, max(0.0, reranker_score if reranker_score is not None else 0.5))

    # Combine: weighted average
    confidence = (
        avg_quality * 0.35  # Source quality: 35%
        + count_factor * 0.20  # Source count: 20%
        + avg_freshness * 0.15  # Freshness: 15%
        + sim_factor * 0.15  # Similarity: 15%
        + rerank_factor * 0.15  # Reranker: 15%
    )

    # Clamp to 0.0–1.0
    confidence = max(0.0, min(1.0, confidence))

    # Label
    if confidence >= 0.8:
        label = "high"
    elif confidence >= 0.5:
        label = "medium"
    elif confidence >= 0.2:
        label = "low"
    else:
        label = "insufficient"

    return {
        "confidence_score": round(confidence, 4),
        "confidence_label": label,
        "breakdown": {
            "source_quality": round(avg_quality, 4),
            "source_count": len(sources),
            "source_count_factor": round(count_factor, 4),
            "freshness": round(avg_freshness, 4),
            "query_similarity": round(sim_factor, 4),
            "reranker_score": round(rerank_factor, 4),
        },
    }
