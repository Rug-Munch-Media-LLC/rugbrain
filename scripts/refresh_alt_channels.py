"""Refresh + VET the alt-ingest channel footprint, then join what's missing.

Operator directive: real broadcast channels only, no garbage. The vetting uses
Telegram's own entity flags (broadcast / megagroup / scam / fake / restricted)
plus a subscriber floor and a junk-name denylist. Groups and user accounts are
never swept. Rejected channels are reported with their reason and never written.

Also ATTEMPTS to join the bot-core channels the account is missing (flood-waits
are reported, not fatal). Writes ONLY data/alt_ingest_extra_channels.txt — the
bot's pinned core in alt_ingest_channels.py is never edited.
"""

from __future__ import annotations

import asyncio
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from rugbrain.ingest_sources.alt_ingest_channels import PINNED_CHANNELS
from rugbrain.ingest_sources.alt_ingest_vet import vet
from rugbrain.ingest_sources.alt_ingest_client import build_alt_ingest_client

OUT = Path(__file__).resolve().parents[1] / "data" / "alt_ingest_extra_channels.txt"


async def main() -> None:
    client = build_alt_ingest_client()
    await client.start()
    kept: dict[str, int] = {}
    rejected: list[tuple[str, str]] = []
    groups = 0
    async for d in client.iter_dialogs():
        username = getattr(d.entity, "username", None)
        if not username:
            continue
        if d.is_user or d.is_group:
            groups += 1
            continue
        reason = vet(username, d.entity)
        if reason:
            rejected.append((username.lower(), reason))
        else:
            kept[username.lower()] = int(getattr(d.entity, "participants_count", 0) or 0)
    joined_dialogs = set(kept) | {u for u, _ in rejected}

    core = [c.lower().lstrip("@") for c in PINNED_CHANNELS]
    missing = [c for c in core if c not in joined_dialogs]
    from telethon.tl.functions.channels import JoinChannelRequest

    join_ok, blocked = 0, []
    for handle in missing:
        try:
            await client(JoinChannelRequest(handle))
            join_ok += 1
        except Exception as exc:  # noqa: BLE001 — flood/private: report, continue
            blocked.append(f"{handle}:{str(exc)[:60]}")

    extras = sorted(set(kept) - set(core))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "# alt-account footprint: vetted broadcast channels (operator: real channels only)\n"
        "# generated by scripts/refresh_alt_channels.py\n"
        + "\n".join(extras) + "\n",
        encoding="utf-8",
    )
    await client.disconnect()
    print(f"kept={len(kept)} extras={len(extras)} total={len(core) + len(extras)} "
          f"groups_or_users_skipped={groups}")
    for reason, n in Counter(r for _, r in rejected).most_common():
        print(f"  reject[{reason}]={n}")
    print(f"join_attempted={len(missing)} join_ok={join_ok} join_blocked={len(blocked)}")
    for b in blocked[:8]:
        print("BLOCKED", b)


asyncio.run(main())
