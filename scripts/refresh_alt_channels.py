"""Refresh + VET the alt-account channel footprint, join what's missing.

Operator directive (2026-10-12):
  * the NEWS sweep covers REAL broadcast channels only (see alt_ingest_vet);
  * the REJECTED channels are NOT discarded — they become the scam/shill
    watchlist (data/alt_ingest_scam_watchlist.txt) that
    scripts/ingest_scam_watchlist.py monitors.

Only data/alt_ingest_extra_channels.txt (footprint) and the watchlist file are
written here; the bot's pinned core in alt_ingest_channels.py is never edited.
"""

from __future__ import annotations

import asyncio
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from rugbrain.ingest_sources.alt_ingest_channels import PINNED_CHANNELS
from rugbrain.ingest_sources.alt_ingest_client import build_alt_ingest_client
from rugbrain.ingest_sources.alt_ingest_vet import vet

DATA = Path(__file__).resolve().parents[1] / "data"
OUT = DATA / "alt_ingest_extra_channels.txt"
OUT_WATCH = DATA / "alt_ingest_scam_watchlist.txt"


async def main() -> None:
    client = build_alt_ingest_client()
    await client.start()
    kept: dict[str, int] = {}
    rejected: list[tuple[str, str, int]] = []
    non_channels = 0
    async for d in client.iter_dialogs():
        username = getattr(d.entity, "username", None)
        if not username:
            continue
        if d.is_user or d.is_group:
            non_channels += 1
            continue
        name = username.lower()
        subs = int(getattr(d.entity, "participants_count", 0) or 0)
        reason = vet(name, d.entity)
        if reason:
            rejected.append((name, reason, subs))
        else:
            kept[name] = subs
    await client.disconnect()

    core = [c.lower().lstrip("@") for c in PINNED_CHANNELS]
    extras = sorted(set(kept) - set(core))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "# alt-account footprint: vetted broadcast channels (operator: real channels only)\n"
        "# generated by scripts/refresh_alt_channels.py\n" + "\n".join(extras) + "\n",
        encoding="utf-8",
    )
    # our own publishing channels are rejected for a NON-scam reason (we post
    # there) — they must never land on the scam watchlist.
    watch = [(n, r, s) for n, r, s in rejected if r != "our_own"]
    OUT_WATCH.write_text(
        "# rejected-for-news channels, monitored as scam/shill watchlist\n"
        "# generated by scripts/refresh_alt_channels.py\n"
        "# handle\treason\tsubscribers\n"
        + "\n".join(f"{n}\t{r}\t{s}" for n, r, s in sorted(watch)) + "\n",
        encoding="utf-8",
    )
    print(f"kept={len(kept)} extras={len(extras)} total={len(core) + len(extras)} "
          f"watchlist={len(watch)} non_channels={non_channels}")
    for reason, n in Counter(r for _, r, _ in rejected).most_common():
        print(f"  reject[{reason}]={n}")


asyncio.run(main())
